/**
 * English / Turkish, exactly like the web dashboard: the English text is the
 * key and [TR] holds the Turkish version. The table below the marker was
 * generated from serverside/dashboard.html (const TR = {...}); app-only
 * strings are added at the end.
 */
object I18n {
    /** "en" or "tr". Reading it from a composable makes it recompose on change. */
    var lang by mutableStateOf(if (Locale.getDefault().language == "tr") "tr" else "en")

    val locale: Locale get() = if (lang == "tr") Locale.forLanguageTag("tr-TR") else Locale.getDefault()
}

/** t("Used {a} of {b}", "a" to x, "b" to y) */
fun t(key: String, vararg vars: Pair<String, Any?>): String {
    var s = if (I18n.lang == "tr") TR[key] ?: key else key
    if (vars.isNotEmpty()) {
        s = Regex("\\{(\\w+)\\}").replace(s) { m ->
            val name = m.groupValues[1]
            vars.firstOrNull { it.first == name }?.second?.toString() ?: m.value
        }
    }
    return s
}

